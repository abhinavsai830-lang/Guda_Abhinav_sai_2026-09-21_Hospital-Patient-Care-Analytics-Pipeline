def generate_patients() -> pd.DataFrame:
    """
    Generate synthetic patient-registration data.

    The raw data intentionally contains data-quality issues
    that will later be handled by the Transform stage.
    """

    patient_ids = [
        f"P{i:04d}"
        for i in range(1, N_PATIENTS + 1)
    ]

    # --------------------------------------------------------
    # Generate ages
    # --------------------------------------------------------

    ages = RNG.integers(
        low=2,
        high=90,
        size=N_PATIENTS,
    )

    # --------------------------------------------------------
    # Generate dates of birth
    # --------------------------------------------------------

    date_of_birth = []

    for age in ages:

        random_days = int(
            RNG.integers(
                low=0,
                high=365,
            )
        )

        dob = (
            START_DATE
            - pd.DateOffset(
                years=int(age)
            )
            - pd.Timedelta(
                days=random_days
            )
        )

        date_of_birth.append(
            dob.date()
        )

    # --------------------------------------------------------
    # Generate names
    # --------------------------------------------------------

    names = []

    for _ in patient_ids:

        first_name = RNG.choice(
            FIRST_NAMES
        )

        last_name = RNG.choice(
            LAST_NAMES
        )

        name = f"{first_name} {last_name}"

        # 20% contain extra spaces
        if RNG.random() < 0.20:
            name = f" {name} "

        names.append(name)

    # --------------------------------------------------------
    # Generate inconsistent gender values
    # --------------------------------------------------------

    genders = RNG.choice(
        [
            "M",
            "Male",
            "male",
            "F",
            "Female",
            "female",
        ],
        size=N_PATIENTS,
    )

    # --------------------------------------------------------
    # Generate cities
    # --------------------------------------------------------

    cities = RNG.choice(
        CITIES,
        size=N_PATIENTS,
    )

    # --------------------------------------------------------
    # Generate blood groups
    # --------------------------------------------------------

    blood_groups = RNG.choice(
        BLOOD_GROUPS,
        size=N_PATIENTS,
    )

    # --------------------------------------------------------
    # Generate chronic conditions
    # --------------------------------------------------------

    chronic_conditions = []

    for age in ages:

        if age < 30:

            condition = RNG.choice(
                [
                    "None",
                    "Asthma",
                ],
                p=[
                    0.92,
                    0.08,
                ],
            )

        else:

            condition = RNG.choice(
                CHRONIC_CONDITIONS,
                p=[
                    0.45,
                    0.15,
                    0.15,
                    0.10,
                    0.08,
                    0.07,
                ],
            )

        chronic_conditions.append(
            condition
        )

    # --------------------------------------------------------
    # Generate registration dates
    # --------------------------------------------------------

    registration_dates = []

    for _ in patient_ids:

        days_before_registration = int(
            RNG.integers(
                low=0,
                high=700,
            )
        )

        registration_date = (
            START_DATE
            - pd.Timedelta(
                days=days_before_registration
            )
        )

        registration_dates.append(
            registration_date.date()
        )

    # --------------------------------------------------------
    # Build DataFrame
    # --------------------------------------------------------

    patients = pd.DataFrame(
        {
            "patient_id": patient_ids,
            "name": names,
            "gender": genders,
            "date_of_birth": date_of_birth,
            "city": cities,
            "blood_group": blood_groups,
            "chronic_condition": chronic_conditions,
            "registration_date": registration_dates,
        }
    )

    # ========================================================
    # INTENTIONAL DATA-QUALITY PROBLEMS
    # ========================================================

    # --------------------------------------------------------
    # Missing blood groups
    # --------------------------------------------------------

    missing_blood_group_indices = RNG.choice(
        N_PATIENTS,
        size=10,
        replace=False,
    )

    patients.loc[
        missing_blood_group_indices,
        "blood_group",
    ] = np.nan

    # --------------------------------------------------------
    # Missing cities
    # --------------------------------------------------------

    missing_city_indices = RNG.choice(
        N_PATIENTS,
        size=8,
        replace=False,
    )

    patients.loc[
        missing_city_indices,
        "city",
    ] = np.nan

    # --------------------------------------------------------
    # Represent "None" as missing in raw source
    # --------------------------------------------------------

    patients.loc[
        patients["chronic_condition"] == "None",
        "chronic_condition",
    ] = np.nan

    # --------------------------------------------------------
    # Duplicate patient registrations
    # --------------------------------------------------------

    duplicate_rows = patients.sample(
        n=6,
        random_state=42,
    )

    patients = pd.concat(
        [
            patients,
            duplicate_rows,
        ],
        ignore_index=True,
    )

    # --------------------------------------------------------
    # Save
    # --------------------------------------------------------

    os.makedirs(
        RAW_DIR,
        exist_ok=True,
    )

    output_path = SOURCE_FILES["patients"]

    patients.to_csv(
        output_path,
        index=False,
    )

    return patients


