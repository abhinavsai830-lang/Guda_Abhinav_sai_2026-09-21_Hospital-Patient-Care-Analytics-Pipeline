def generate_appointments(
    patients: pd.DataFrame,
) -> pd.DataFrame:
    """
    Generate synthetic appointment-scheduling data.

    The data contains:
    - completed appointments
    - no-shows
    - cancellations
    - realistic waiting times
    - intentionally invalid records
    - unknown patient IDs
    """

    # --------------------------------------------------------
    # Use unique patient IDs.
    #
    # The patient source contains duplicate registrations,
    # but the appointment system should normally reference
    # logical patients.
    # --------------------------------------------------------

    valid_patient_ids = (
        patients["patient_id"]
        .drop_duplicates()
        .tolist()
    )

    rows = []

    # --------------------------------------------------------
    # Generate appointments
    # --------------------------------------------------------

    for i in range(
        1,
        N_APPOINTMENTS + 1,
    ):

        # Pick department
        department = RNG.choice(
            list(DEPARTMENTS.keys())
        )

        # Pick doctor from department
        doctor_id = RNG.choice(
            DEPARTMENTS[department]
        )

        # Pick patient
        patient_id = RNG.choice(
            valid_patient_ids
        )

        # Random appointment day
        day_offset = int(
            RNG.integers(
                low=0,
                high=45,
            )
        )

        appointment_day = (
            START_DATE
            + pd.Timedelta(
                days=day_offset
            )
        )

        # ----------------------------------------------------
        # Hospital appointment hours
        # ----------------------------------------------------

        hour = int(
            RNG.choice(
                [
                    9,
                    10,
                    11,
                    12,
                    13,
                    14,
                    15,
                    16,
                ],
                p=[
                    0.12,
                    0.20,
                    0.20,
                    0.15,
                    0.08,
                    0.10,
                    0.08,
                    0.07,
                ],
            )
        )

        minute = int(
            RNG.choice(
                [
                    0,
                    15,
                    30,
                    45,
                ]
            )
        )

        scheduled_time = (
            appointment_day
            + pd.Timedelta(
                hours=hour,
                minutes=minute,
            )
        )

        # ----------------------------------------------------
        # Appointment status
        # ----------------------------------------------------

        status = RNG.choice(
            [
                "Completed",
                "No-Show",
                "Cancelled",
            ],
            p=[
                0.82,
                0.12,
                0.06,
            ],
        )

        checkin_time = pd.NaT
        consultation_start_time = pd.NaT

        # ----------------------------------------------------
        # Completed appointment
        # ----------------------------------------------------

        if status == "Completed":

            # Patient checks in slightly before or after
            # the scheduled time.

            checkin_offset = int(
                RNG.integers(
                    low=-15,
                    high=10,
                )
            )

            checkin_time = (
                scheduled_time
                + pd.Timedelta(
                    minutes=checkin_offset
                )
            )

            # Base consultation waiting time
            base_wait_by_department = {
                "Cardiology": 35,
                "General Medicine": 45,
                "Orthopedics": 30,
                "Pediatrics": 20,
                "Neurology": 25,
                "Pulmonology": 25,
            }

            base_wait = (
                base_wait_by_department[
                    department
                ]
            )

            # Morning rush
            peak_wait = (
                20
                if hour in (10, 11)
                else 0
            )

            waiting_time = max(
                2,
                int(
                    RNG.normal(
                        base_wait + peak_wait,
                        12,
                    )
                ),
            )

            consultation_start_time = (
                checkin_time
                + pd.Timedelta(
                    minutes=waiting_time
                )
            )

        rows.append(
            [
                f"A{i:05d}",
                patient_id,
                doctor_id,
                department,
                scheduled_time,
                checkin_time,
                consultation_start_time,
                status,
            ]
        )

    # --------------------------------------------------------
    # Create DataFrame
    # --------------------------------------------------------

    appointments = pd.DataFrame(
        rows,
        columns=[
            "appointment_id",
            "patient_id",
            "doctor_id",
            "department",
            "scheduled_time",
            "checkin_time",
            "consultation_start_time",
            "status",
        ],
    )

    # ========================================================
    # INTENTIONAL DATA-QUALITY PROBLEMS
    # ========================================================

    # --------------------------------------------------------
    # 1. Unknown patient IDs
    # --------------------------------------------------------
    #
    # These patients don't exist in patients.csv.
    #
    # This will later test referential integrity.
    # --------------------------------------------------------

    unknown_patient_indices = RNG.choice(
        len(appointments),
        size=5,
        replace=False,
    )

    appointments.loc[
        unknown_patient_indices,
        "patient_id",
    ] = "P9999"

    # --------------------------------------------------------
    # 2. Invalid timestamps
    # --------------------------------------------------------
    #
    # consultation_start_time occurs before check-in.
    #
    # This creates a negative waiting time.
    # --------------------------------------------------------

    completed_indices = appointments.index[
        appointments["status"] == "Completed"
    ]

    invalid_time_indices = RNG.choice(
        completed_indices,
        size=8,
        replace=False,
    )

    appointments.loc[
        invalid_time_indices,
        "consultation_start_time",
    ] = (
        appointments.loc[
            invalid_time_indices,
            "checkin_time",
        ]
        - pd.Timedelta(
            minutes=30
        )
    )

    # --------------------------------------------------------
    # Save
    # --------------------------------------------------------

    output_path = SOURCE_FILES[
        "appointments"
    ]

    appointments.to_csv(
        output_path,
        index=False,
    )

    return appointments
